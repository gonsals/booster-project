import { test, expect } from "@playwright/test";

test("public previews appear in the pack with sources and unknown odds instead of zero", async ({ page }) => {
    const errors: string[] = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.goto("/sets/boosters/mdd");
    await expect(page.getByRole("heading", { name: "Marvel: Darkhold Destiny", exact: true })).toBeVisible();
    const grid = page.getByRole("region", { name: "Cartas de sobres" });
    const payload = JSON.parse(await page.locator("#card-detail-data").textContent() ?? "{}");
    const previews = payload.cards.filter((card: { provisional: boolean; preview: boolean }) => card.preview && card.provisional);
    expect(previews.length).toBeGreaterThan(0);
    expect(await grid.locator("article").count()).toBe(payload.cards.length);
    const detail = previews.find((card: { reveal?: { source_uri?: string } }) => card.reveal?.source_uri) ?? previews[0];
    const article = grid.locator(`article[data-card-id="${detail.id}"]`);
    await expect(article).toContainText("Sobre por confirmar");
    let requests = 0;
    page.on("request", request => { if (["document", "fetch", "xhr"].includes(request.resourceType())) requests++; });
    await article.getByRole("button", { name: /^Ver detalles/ }).click();
    const modal = page.getByRole("dialog");
    await expect(modal).toBeVisible();
    await expect(modal).toContainText("Adelanto publicado");
    await expect(page.locator("#modal-chance")).toHaveText("—");
    await expect(page.locator("#modal-ratio")).toHaveText("");
    await expect(page.locator("#modal-odds-caption")).toContainText("todavía no se ha confirmado");
    if (detail.reveal?.source_uri) await expect(page.locator("#modal-preview-source")).toHaveAttribute("href", detail.reveal.source_uri);
    if (detail.reveal?.previewed_at) await expect(page.locator("#modal-preview-date")).toContainText(detail.reveal.previewed_at);
    await page.screenshot({ path: "test-results/preview-modal.png" });
    expect(requests).toBe(0);
    await page.keyboard.press("Escape");
    await expect(modal).toBeHidden();
    await page.getByLabel("Sobre", { exact: true }).selectOption("standard");
    await page.getByRole("button", { name: "Aplicar", exact: true }).click();
    await expect(page.locator("#page-loader")).toBeHidden();
    await expect(grid.locator("article")).toHaveCount(payload.cards.length);
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: "test-results/previews-mobile.png", fullPage: true });
    expect(errors).toEqual([]);
});
